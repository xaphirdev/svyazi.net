CREATE TABLE IF NOT EXISTS incidents (
  id INTEGER PRIMARY KEY __AUTO_INCREMENT__,
  engineer_id INTEGER,
  INDEX idx_begin (BEGIN_TIME),
  INDEX idx_end (END_TIME),
  INDEX idx_assignment (engineer_id, BEGIN_TIME),
  INDEX idx_repeat (SERV_ELEM(100), BEGIN_TIME),
  seed_key VARCHAR(180) UNIQUE,
  source_data TEXT,
  revision INTEGER NOT NULL DEFAULT 1,
  PW VARCHAR(450) NOT NULL,
  NAPR VARCHAR(450) NOT NULL,
  TEHC VARCHAR(450) NOT NULL,
  KATEG TINYINT,
  CAT_LEGACY VARCHAR(32),
  NETW_TYPE VARCHAR(450) NOT NULL,
  SERV_ELEM VARCHAR(450) NOT NULL,
  NUMB_RBS INT,
  RBS_SECTOR INTEGER NOT NULL DEFAULT 0,
  EQIP_TYPE VARCHAR(450) NOT NULL,
  ALARM_TYPE VARCHAR(450) NOT NULL,
  DESCR VARCHAR(450) NOT NULL,
  BEGIN_TIME DATETIME NOT NULL,
  END_TIME DATETIME NOT NULL,
  AKB TIME,
  DGU TIME,
  LENGHT VARCHAR(450) NOT NULL,
  PROSTOY TIME,
  COMMON_PROSTOY TIME,
  AKB_SECONDS BIGINT,
  DGU_SECONDS BIGINT,
  PROSTOY_SECONDS BIGINT,
  COMMON_PROSTOY_SECONDS BIGINT,
  ALARM_WHO VARCHAR(450) NOT NULL,
  DESC_NOTICE VARCHAR(450) NOT NULL
) __TABLE_OPTIONS__
